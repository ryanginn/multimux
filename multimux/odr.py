"""Generate ODR-DabMux / ODR-DabMod configuration files."""

ETI_TOKEN = "%ETI_PORT%"


def default_mux_config(block, index):
    """A minimal, valid ODR-DabMux config with one DAB+ service fed over ZMQ.

    Feed it with e.g.:
      odr-audioenc -i stream.wav -b 96 -o tcp://localhost:<audio port>
    """
    audio_port = 9000 + index * 10 + 1
    eid = 0xCE10 + index
    sid = 0xC0A0 + index * 16 + 1
    return f"""; ODR-DabMux configuration for block {block}
; Leave the ETI_PORT placeholder in "outputs": multimux fills in the port.
general {{
    dabmode 1
    nbframes 0
    syslog false
    tist false
    managementport 0
}}

remotecontrol {{
    telnetport 0
}}

ensemble {{
    id 0x{eid:04X}
    ecc 0xE3
    local-time-offset auto
    label "MultiMux {block}"
    shortlabel "MM {block}"
}}

services {{
    srv-1 {{
        id 0x{sid:04X}
        label "Station {block}-1"
        shortlabel "St{block}"
    }}
}}

subchannels {{
    sub-1 {{
        type dabplus
        ; ODR-AudioEnc sends to this port: -o tcp://localhost:{audio_port}
        inputfile "tcp://*:{audio_port}"
        inputproto zmq
        zmq-buffer 40
        zmq-prebuffering 20
        bitrate 96
        id 1
        protection 3
    }}
}}

components {{
    comp-1 {{
        service srv-1
        subchannel sub-1
    }}
}}

outputs {{
    zmq "zmq+tcp://*:{ETI_TOKEN}"
    ; paces the mux in real time (no hardware output on this side)
    throttle "simul://"
}}
"""


def render_mux_config(channel):
    return channel["mux_config"].replace(ETI_TOKEN, str(channel["eti_port"]))


def render_mod_config(channel):
    return f"""; generated by multimux for block {channel['block']} - do not edit
[remotecontrol]
telnet=0

[log]
syslog=0
filelog=0

[input]
transport=zeromq
source=tcp://localhost:{channel['eti_port']}
max_frames_queued=400

[modulator]
gainmode=var
digital_gain={float(channel.get('mod_digital_gain', 0.8))}
rate=2048000

[cfr]
enable=0

[firfilter]
enabled=1

[output]
output=zmq

[zmqoutput]
listen=tcp://*:{channel['iq_port']}
socket_type=pub
"""
