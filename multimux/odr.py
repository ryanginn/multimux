"""Generate ODR-DabMod configuration files for each channel's input feed."""

# input_type -> (ODR-DabMod transport, example source, description)
INPUT_TYPES = {
    "zmq": ("zeromq", "tcp://192.168.1.10:9100",
            "ETI over ZeroMQ from ODR-DabMux (outputs: zmq \"zmq+tcp://*:9100\")"),
    "edi": ("edi", "tcp://192.168.1.10:9201",
            "EDI over TCP (tcp://host:port) or UDP (udp://:12000, udp://@239.1.1.1:12000)"),
    "eti_tcp": ("tcp", "tcp://192.168.1.10:9300", "Raw ETI over TCP"),
    "eti_file": ("file", "/path/to/feed.eti", "ETI file or named pipe"),
    "iq": (None, "tcp://192.168.1.20:54001",
           "IQ from a remote ODR-DabMod ZMQ PUB output (no local modulator)"),
}


def runs_modulator(channel):
    return channel["input_type"] != "iq"


def combiner_endpoint(channel):
    """Where the combiner subscribes for this channel's 2.048 MS/s IQ."""
    if channel["input_type"] == "iq":
        return channel["source"]
    return f"tcp://127.0.0.1:{channel['iq_port']}"


def render_mod_config(channel):
    transport = INPUT_TYPES[channel["input_type"]][0]
    extra = ""
    if transport == "zeromq":
        extra = "max_frames_queued=400\n"
    elif transport == "edi":
        extra = "edi_max_delay=240\n"
    elif transport == "file":
        extra = "loop=0\n"
    return f"""; generated by multimux for block {channel['block']} - do not edit
[remotecontrol]
telnet=0

[log]
syslog=0
filelog=0

[input]
transport={transport}
source={channel['source']}
{extra}
[modulator]
gainmode=var
digital_gain={float(channel.get('mod_digital_gain', 0.8))}
rate=2048000

[cfr]
enable=0

[firfilter]
enabled=1

[output]
output=zmq

[zmqoutput]
listen=tcp://127.0.0.1:{channel['iq_port']}
socket_type=pub
"""
